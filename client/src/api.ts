/**
 * api.ts - 后端 API 类型定义与调用封装
 *
 * 与后端 server/types/ 下的类型手动对齐。
 * 统一处理 ApiResponse<T> 契约：成功取 data，失败抛出带 code 的 Error。
 */

// ==========================================
// 后端响应契约
// ==========================================

interface ApiSuccess<T> {
  success: true;
  data: T;
}

interface ApiFailure {
  success: false;
  error: {
    code: string;
    message: string;
    details?: unknown;
  };
}

type ApiResponse<T> = ApiSuccess<T> | ApiFailure;

// ==========================================
// 领域类型（与后端对齐）
// ==========================================

export interface VideoInfo {
  id: string;
  title: string;
  duration?: number;
  thumbnails: { url: string; width?: number; height?: number }[];
  uploadDate?: string;
  channelTitle?: string;
  playlistTitle?: string;
  playlistIndex?: number;
  formats: VideoFormat[];
  subtitles: SubtitleInfo[];
}

export interface VideoFormat {
  formatId: string;
  container: string;
  qualityLabel: string;
  resolution?: string;
  filesize?: number;
  hasVideo: boolean;
  hasAudio: boolean;
  codec?: string;
}

export interface SubtitleInfo {
  language: string;
  name: string;
  isAutoGenerated: boolean;
}

export type ResolveResult =
  | { kind: 'video'; title: string; videos: [VideoInfo] }
  | {
      kind: 'playlist' | 'channel';
      title: string;
      channelTitle?: string;
      videoCount: number;
      videos: VideoInfo[];
    };

export type DownloadStatus =
  | 'queued'
  | 'downloading'
  | 'completed'
  | 'failed'
  | 'cancelled'
  | 'paused';

