/**
 * api.ts - 后端 API 类型定义与调用封装
 *
 * 与后端 server/types/ 下的类型手动对齐。
 * 统一处理 ApiResponse<T> 契约：成功取 data，失败抛出带 code 的 Error。
 */

// ==========================================
// 后端响应契约
// ==========================================

interface ApiSuccess<T> {
  success: true;
  data: T;
}

interface ApiFailure {
  success: false;
  error: {
    code: string;
    message: string;
    details?: unknown;
  };
}

type ApiResponse<T> = ApiSuccess<T> | ApiFailure;

