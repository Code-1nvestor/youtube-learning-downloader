export const api = {
  getHealth: () => request<HealthStatus>('/health'),
  getSettings: () => request<AppSettingsStatus>('/settings'),
  updateSettings: (settings: UpdateAppSettingsInput) =>
    request<AppSettingsStatus>('/settings', {
      method: 'PUT',
      body: JSON.stringify(settings),
    }),

  // 解析
  resolve: (url: string) =>
    request<ResolveResult>(`/resolve?url=${encodeURIComponent(url)}`),

  // 下载
  createDownload: (tasks: CreateDownloadTaskInput[]) =>
    request<{ taskIds: string[] }>('/download', {
      method: 'POST',
      body: JSON.stringify({ tasks }),
    }),

  getFormats: (url: string) =>
    request<{ videoId: string; title: string; formats: VideoFormat[]; subtitles: SubtitleInfo[] }>(
      `/download/formats?url=${encodeURIComponent(url)}`,
    ),

  // 队列
  getQueue: () => request<QueueStatus>('/queue'),

  pauseTask: (id: string) =>
    request<QueueStatus>(`/queue/${id}/pause`, { method: 'POST' }),

  resumeTask: (id: string) =>
    request<QueueStatus>(`/queue/${id}/resume`, { method: 'POST' }),

  cancelTask: (id: string) =>
    request<QueueStatus>(`/queue/${id}/cancel`, { method: 'POST' }),

  removeTask: (id: string) =>
    request<QueueStatus>(`/queue/${id}`, { method: 'DELETE' }),

  // 历史
  getHistory: (page = 1, pageSize = 50) =>
    request<HistoryPage>(`/history?page=${page}&pageSize=${pageSize}`),

  deleteHistory: (id: string) =>
    request<{ deleted: boolean; id: string }>(`/history/${id}`, {
      method: 'DELETE',
    }),

  clearHistory: () =>
    request<{ deleted: number }>('/history', { method: 'DELETE' }),

  // Cookie
  getCookieStatus: () => request<CookieStatus>('/auth/cookie'),

  setCookieFile: (content: string) =>
    request<CookieStatus>('/auth/cookie/file', {
      method: 'POST',
      body: JSON.stringify({ content }),
    }),

  setCookieBrowser: (browser: string) =>
    request<CookieStatus>('/auth/cookie/browser', {
      method: 'POST',
      body: JSON.stringify({ browser }),
    }),

  clearCookie: () =>
    request<CookieStatus>('/auth/cookie', { method: 'DELETE' }),

  // 字幕
  previewSubtitle: (url: string, language: string, autoGenerated: boolean, maxCues = 5) =>
    request<{
      videoTitle: string;
      language: string;
      languageName: string;
      isAutoGenerated: boolean;
      cues: { index: number; start: number; end: number; startTimestamp: string; text: string }[];
      totalCount: number;
      truncated: boolean;
    }>(
      `/subtitle/preview?url=${encodeURIComponent(url)}&language=${encodeURIComponent(language)}&autoGenerated=${autoGenerated}&maxCues=${maxCues}`,
    ),
};
